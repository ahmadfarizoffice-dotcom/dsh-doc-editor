#!/usr/bin/env node
/**
 * Generates `packages/core/src/layout/afm-metrics.ts` from the Adobe Font
 * Metrics files bundled with PDFKit.
 *
 * The layout engine needs real advance widths for deterministic line breaking.
 * Standard-14 metrics are public data; embedding them keeps the engine
 * dependency-free at runtime and makes PDF and HTML layout agree.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..");
const pdfkitData = resolve(
  repo,
  "node_modules/.pnpm/pdfkit@0.20.2/node_modules/pdfkit/js/data",
);

const FONTS = [
  ["helvetica", "Helvetica.afm", "Helvetica"],
  ["helveticaBold", "Helvetica-Bold.afm", "Helvetica-Bold"],
  ["helveticaOblique", "Helvetica-Oblique.afm", "Helvetica-Oblique"],
  [
    "helveticaBoldOblique",
    "Helvetica-BoldOblique.afm",
    "Helvetica-BoldOblique",
  ],
  ["times", "Times-Roman.afm", "Times-Roman"],
  ["timesBold", "Times-Bold.afm", "Times-Bold"],
  ["timesItalic", "Times-Italic.afm", "Times-Italic"],
  ["timesBoldItalic", "Times-BoldItalic.afm", "Times-BoldItalic"],
  ["courier", "Courier.afm", "Courier"],
  ["courierBold", "Courier-Bold.afm", "Courier-Bold"],
  ["courierOblique", "Courier-Oblique.afm", "Courier-Oblique"],
  ["courierBoldOblique", "Courier-BoldOblique.afm", "Courier-BoldOblique"],
];

function parseAfm(source) {
  const metrics = new Map();
  let ascender = 0.75;
  let descender = -0.25;
  let defaultWidth = 556;
  for (const line of source.split(/\r?\n/)) {
    if (line.startsWith("C ")) {
      const code = /C\s+(-?\d+)\s*;/.exec(line);
      const width = /WX\s+(\d+)\s*;/.exec(line);
      if (!code || !width) continue;
      const cp = Number(code[1]);
      if (cp >= 32 && cp <= 255) metrics.set(cp, Number(width[1]));
    } else if (line.startsWith("Ascender ")) {
      ascender = Number(line.split(/\s+/)[1]) / 1000;
    } else if (line.startsWith("Descender ")) {
      descender = Number(line.split(/\s+/)[1]) / 1000;
    } else if (line.startsWith("AvgWidth ")) {
      const value = Number(line.split(/\s+/)[1]);
      if (Number.isFinite(value) && value > 0) defaultWidth = value;
    }
  }
  const widths = [];
  for (let cp = 32; cp <= 255; cp += 1)
    widths.push(metrics.get(cp) ?? defaultWidth);
  const space = metrics.get(32) ?? 278;
  return { widths, ascender, descender, defaultWidth, space };
}

const lines = [];
lines.push("/**");
lines.push(
  " * Generated by tools/generate-font-metrics.mjs - do not edit by hand.",
);
lines.push(" *");
lines.push(
  " * Advance widths (1/1000 em) for the PDF standard-14 fonts, indexed by",
);
lines.push(
  " * codepoint - 32 for U+0020..U+00FF. Used for deterministic line breaking.",
);
lines.push(" */");
lines.push("");
lines.push("export interface AfmMetrics {");
lines.push("  /** Advance widths in 1/1000 em for codepoints 32..255. */");
lines.push("  widths: readonly number[];");
lines.push("  /** Font ascender as a fraction of the em square. */");
lines.push("  ascender: number;");
lines.push(
  "  /** Font descender as a fraction of the em square (negative). */",
);
lines.push("  descender: number;");
lines.push(
  "  /** Width used for codepoints outside the table, in 1/1000 em. */",
);
lines.push("  defaultWidth: number;");
lines.push("  space: number;");
lines.push("}");
lines.push("");

const names = [];
for (const [key, file, label] of FONTS) {
  const source = await readFile(resolve(pdfkitData, file), "utf8");
  const parsed = parseAfm(source);
  names.push(key);
  lines.push(`/** ${label} */`);
  lines.push(`export const ${key}: AfmMetrics = {`);
  lines.push(`  widths: [${parsed.widths.join(",")}],`);
  lines.push(`  ascender: ${parsed.ascender},`);
  lines.push(`  descender: ${parsed.descender},`);
  lines.push(`  defaultWidth: ${parsed.defaultWidth},`);
  lines.push(`  space: ${parsed.space},`);
  lines.push("};");
  lines.push("");
}

lines.push("export const AFM_METRICS: Record<string, AfmMetrics> = {");
for (const name of names) {
  lines.push(`  ${name},`);
}
lines.push("};");
lines.push("");
lines.push("/** Metrics for a font key, defaulting to Helvetica. */");
lines.push("export function metricsFor(key: string): AfmMetrics {");
lines.push("  return AFM_METRICS[key] ?? helvetica;");
lines.push("}");

const outDir = resolve(repo, "packages/core/src/layout");
await mkdir(outDir, { recursive: true });
await writeFile(
  resolve(outDir, "afm-metrics.ts"),
  lines.join("\n") + "\n",
  "utf8",
);
console.log(
  `Wrote packages/core/src/layout/afm-metrics.ts (${lines.length} lines, ${names.length} fonts)`,
);
